"""Write docs/RUNBOOK.md, the handover for the team that will run the agent, from the configuration it describes.
CI regenerates it, so the runbook cannot drift from what is deployed."""

from __future__ import annotations

import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    policy = tomllib.loads((ROOT / "config" / "policy.toml").read_text())
    releases = tomllib.loads((ROOT / "config" / "releases.toml").read_text())
    prices = tomllib.loads((ROOT / "config" / "models.toml").read_text())["models"]
    release = json.loads((ROOT / "config" / "release.json").read_text())
    dev = json.loads((ROOT / "reports" / "dev.json").read_text())
    g = dev["designs"]["guarded"]
    gate = releases["gate"]
    alerts = policy["alerts"]
    held_path = ROOT / "reports" / "heldout.json"
    if held_path.exists():
        h = json.loads(held_path.read_text())["designs"]["guarded"]["personal_data"]
        missed = (
            f"On the held-out world redaction let personal data through in {h['sent_to_the_model']} of "
            f"{h['messages_with_personal_data']:,} messages that held some."
        )
    else:
        missed = "Redaction only knows the formats it was written for."
    rows = "\n".join(f"| {m} | €{p['input']:.2f} | €{p['output']:.2f} |" for m, p in prices.items())
    text = f"""# Runbook: utility customer-service agent

Generated by `scripts/handover.py` from `config/` and `reports/dev.json`. Do not edit by hand; change the
configuration and regenerate.

## What runs where

| Part | Azure resource (infra/terraform) | Owner after handover |
|---|---|---|
| API `POST /v1/messages` | Container App `utility-agent` (1 to 10 replicas, HTTP scaling) | Service platform \
team |
| Model | Azure OpenAI account, one deployment per model name | Service platform team |
| Service passages | Azure AI Search index `service-passages` | Customer service content team |
| Secrets | Key Vault, read by the app's managed identity | Security |
| Traces and alerts | Log Analytics workspace, Application Insights | Service platform team |
| Account data | Billing system API (the customer's own) | Billing IT |

## The release in production

| Setting | Value |
|---|---|
| Release | {release["name"]} |
| Model deployment | {release["model"]} |
| Prompt | {release["prompt"]} |
| Few-shot examples | {"on" if release["few_shot"] else "off"} |
| Hand to a person below confidence | {release["threshold"]} |

Measured on the dev world before handover: {g["right"]}% of messages handled right, {g["harmful_per_1k"]:g} harmful
actions per 1,000, {g["contained"]}% without a person, €{g["eur_per_conversation"]:.4f} model cost per conversation,
p95 model latency {g["p95_model_latency_ms"]} ms.

## Shipping a change

Every change to the model, prompt, examples or threshold is a release and goes through the gate in CI:

1. Add the candidate to `config/releases.toml`.
2. CI runs the golden set against production and the candidate.
3. The release ships only if the paired bootstrap's lower bound of the change in messages handled right is above
   -{100 * gate["max_right_drop"]:.1f} points, the golden set shows no more than {gate["max_extra_harm"]} extra harmful
   actions, and the model cost stays under €{gate["max_eur_per_conversation"]:.3f} per conversation.
4. Deploy as a new Container Apps revision with 10 % of traffic; move to 100 % after a day without alerts.

Add new golden messages for every incident, and keep risky cases (dates, amounts, payment difficulties) over-
represented: a golden set drawn from the traffic mix held too few English dates to stop a model that misread them.

## Alerts

| Alert | Threshold | First step |
|---|---|---|
| Harmful-action reports from reviewers | any | Roll back to the previous revision; add the message to the golden set |
| Share handed to a person | above {100 * alerts["handed_to_people_share"]:.0f} % in an hour | Check model \
deployment health and the confidence distribution |
| Model cost per conversation | above €{alerts["eur_per_conversation"]:.3f} (daily average) | Check token counts \
per span; a prompt or example change may have slipped through |
| p95 latency | above 3 s for 15 minutes | Check Azure OpenAI throttling (429s) and replica count |
| 5xx from the API | above 1 % for 5 minutes | Check the billing API and Key Vault access |

## Rules the agent applies (config/policy.toml)

- Meter readings: accepted between {policy["meter_reading"]["low_factor"]}× and
  {policy["meter_reading"]["high_factor"]}× the expected usage since the last reading; otherwise a person checks.
- Instalments: at least {policy["instalment"]["min_share"]:.0%} of the projected monthly cost.
- Payment plans: up to €{policy["payment_plan"]["max_balance_eur"]:,} in at most {policy["payment_plan"]["max_rates"]}
  rates of at least €{policy["payment_plan"]["min_rate_eur"]}; from dunning stage
  {policy["payment_plan"]["priority_dunning_stage"]}, or with a hardship flag, a person takes over the same day.
- Cancellation of basic supply: {policy["cancellation"]["basic_supply_notice_days"]} days.

## Personal data

Customer numbers and postcodes become placeholders before the model sees a message; IBAN, e-mail, phone, birth date
and signature names are masked. Spans carry decisions, tokens and cost, never message text. {missed} Review the
masked counts per span weekly and add new formats to `redact.py` with a test.

## Costs

Model prices assumed for cost accounting (EUR per million tokens; update `config/models.toml` to the contract):

| Model | Input | Output |
|---|--:|--:|
{rows}
"""
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "RUNBOOK.md").write_text(text)


if __name__ == "__main__":
    main()
